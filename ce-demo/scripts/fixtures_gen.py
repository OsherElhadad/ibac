def dump(name: str, obj: dict) -> None:
    path = OUT / f"{name}.json"
    s = json.dumps(obj, separators=(",", ":"))
    path.write_text(s)
    tokens = count_tokens(s)
    print(f"  {name:<44s} {len(s):>7d} chars  ~{tokens:>6d} tokens")


def main() -> None:
    # Wipe the old SRE fixtures so we don't ship stale ones.
    for p in OUT.glob("*.json"):
        p.unlink()

    print("Generating CE-demo security fixtures:")
    dump("get_user_profile_alice",                 build_user_profile())
    dump("get_session_events_morning",             build_session_events())
    dump("get_session_events_aux",                 build_session_events_aux())
    dump("lookup_ip_reputation_203_0_113_42",      build_ip_reputation())
    dump("lookup_ip_reputation_benign",            build_ip_reputation_benign())
    dump("get_file_access_log_alice_morning",      build_file_access_log())
    dump("get_data_exfil_attempts_alice",          build_data_exfil())
    dump("search_logins_by_ip_203_0_113_42",       build_search_logins_by_ip())
    print("Done.")


