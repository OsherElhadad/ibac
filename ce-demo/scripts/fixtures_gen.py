# ---------- helpers ----------

def pad(rng: random.Random, target_chars: int, build_one, *, relevant=None, relevant_position="middle"):
    """Append records from build_one(i) until the serialized payload hits the target."""
    records = []
    if relevant is not None and relevant_position == "start":
        records.append(relevant)
    i = 0
    while True:
        s = json.dumps(records, separators=(",", ":"))
        if len(s) >= target_chars:
            break
        records.append(build_one(i))
        i += 1
        if i == 10**5:
            break  # safety
    if relevant is not None and relevant_position != "start":
        # Put the signal somewhere in the middle so the LLM has to find it.
        mid = int(len(records) * 0.62)
        records.insert(mid, relevant)
    return records


def hexid(rng: random.Random, n: int) -> str:
    return "".join(rng.choices("0123456789abcdef", k=n))


def ts(rng: random.Random, day: str, hour_range: tuple[int, int] = (0, 23)) -> str:
    h = rng.randint(*hour_range)
    m = rng.randint(0, 59)
    s = rng.randint(0, 59)
    return f"{day}T{h:02d}:{m:02d}:{s:02d}Z"


